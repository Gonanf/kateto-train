# explicit list covers pronouns. Either signal = rioplatense 2nd person.
VOSEO_RE = ("ás", "és", "ís", "aste", "iste", "alo", "elo", "ilo",
            "anos", "ate", "ete", "ite", "ame", "ime", "ime", "anos",
            "ala", "ela", "ila", "á", "é", "í")


def has_voseo(resp):
    import re
    toks = re.findall(r"[a-záéíóúüñ]+", resp.lower())
    if any(w in VOSEO_WORDS for w in toks):
        return True
    return any(w.endswith(e) and len(w) > len(e) + 1
               for w in toks for e in VOSEO_RE)


def build(voice, i):
    cfg = VOICES[voice]
    t = TOPICS[(i * 7 + len(voice)) % len(TOPICS)]
    a = ASPECTS[(i * 23 + len(voice)) % len(ASPECTS)]
    prompt = PROMPTS[(i * 11 + len(voice)) % len(PROMPTS)].format(t=t)
    o = cfg["open"][(i * 13 + len(voice)) % len(cfg["open"])]
    c = cfg["close"][(i * 19 + len(voice) * 3) % len(cfg["close"])]
    if voice == "whisperer":
        frag = W_FRAG[(i * 29 + len(voice) * 7) % len(W_FRAG)].format(t=t)
        frag = frag[0].upper() + frag[1:]
        resp = f"{o} {frag} {c}"
    elif voice == "doktor":
        m1 = cfg["move"][(i * 17 + len(voice)) % len(cfg["move"])]
        m2 = cfg["move"][(i * 29 + len(voice) * 5) % len(cfg["move"])]
        resp = (f"{o} {cfg['wire'].format(t=t, a=a)} Premisa: {m1}. "
                f"Objeción: {m2}. {c} Pensalo y traé tu réplica.")
    else:
        m = cfg["move"][(i * 17 + len(voice)) % len(cfg["move"])]
        resp = f"{o} {cfg['wire'].format(t=t, a=a)} {m.capitalize()}, che. {c}"
    assert has_voseo(resp), f"no-voseo {voice} row {i}: {resp[:80]}"
    min_words = 6 if voice == "whisperer" else 8
    assert "tool_call" not in resp and len(resp.split()) >= min_words, f"bad row {i}"
    return prompt, resp


